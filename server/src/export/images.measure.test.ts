import test from 'node:test';
import assert from 'node:assert/strict';
import { measureImage } from './images';

test('R12 measureImage rejects ICNS/JXL/HEIF-like buffers before image-size parsers', () => {
  const icns = Buffer.from('icns' + 'x'.repeat(64), 'utf8');
  assert.throws(() => measureImage(icns), /不支持的图片格式/);
  const jxl = Buffer.from([0x00, 0x00, 0x00, 0x0c, 0x4a, 0x58, 0x4c, 0x20, 0x0d, 0x0a, 0x87, 0x0a]);
  assert.throws(() => measureImage(jxl), /不支持的图片格式/);
  const png = Buffer.from([
    0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a,
    0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52,
    0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
    0x08, 0x02, 0x00, 0x00, 0x00, 0x90, 0x77, 0x53, 0xde,
  ]);
  const measured = measureImage(png);
  assert.equal(measured.width, 1);
  assert.equal(measured.height, 1);
});
